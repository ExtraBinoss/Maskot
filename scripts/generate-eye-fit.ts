import { writeFileSync } from "node:fs";
import { POUR_TESTS } from "../src/mascot/engine/eyefit";
import { SHAPES } from "../src/mascot/engine/skins";

// These corrections depend only on the built-in shape/state/expression catalogue.
// Run the original solver at build time instead of blocking a user's click.
const solved = POUR_TESTS.batir();
const data = Object.fromEntries(
  SHAPES.map((shape) => [
    shape.id,
    Object.fromEntries(solved.get(shape.radii)!),
  ]),
);
// Preserve signed zero too: the engine's regression contracts compare numbers exactly.
const serialized = JSON.stringify(data, (_key, value: unknown) => Object.is(value, -0) ? "__NEGATIVE_ZERO__" : value)
  .replaceAll('"__NEGATIVE_ZERO__"', "-0");
writeFileSync(new URL("../src/mascot/engine/eye-fit-data.ts", import.meta.url),
  'import type { Point } from "./bot-types";\n// Generated by bun run generate:eye-fit.\nconst data: Record<string, Record<string, Point>> = ' + serialized + ';\nexport default data;\n');
